"""Replaceable application boundaries; implemented by infrastructure adapters."""
from dataclasses import dataclass
from pathlib import Path
from threading import Event
from typing import Callable, Protocol
from jarvis.domain.settings import Settings

class ConversationRepository(Protocol):
    def sessions(self) -> list: ...
    def new_session(self, title: str = "新对话") -> str: ...
    def add_message(self, session_id: str, role: str, content: str, state: dict | None = None) -> None: ...
    def history(self, session_id: str, limit: int = 30) -> list: ...
    def remember(self, content: str) -> int: ...
    def memories(self) -> list: ...
    def recall(self, query: str) -> list: ...
    def counts(self, session_id: str) -> dict: ...

class CloudGateway(Protocol):
    def chat(self, messages: list) -> str: ...
    def chat_stream(self, messages: list, cancel: Event | None = None): ...
    def transcription_client(self) -> "CloudGateway": ...
    def transcribe(self, path: Path) -> str: ...

class AudioPort(Protocol):
    capture_active: bool
    level: float
    stop_event: Event
    def prepare(self) -> None: ...
    def recording(self, settings: Settings) -> Path: ...
    def command_recording(self, settings: Settings) -> Path | None: ...
    def wake_chime(self, settings: Settings) -> None: ...
    def speak(self, text: str, settings: Settings, on_line: Callable | None = None) -> None: ...
    def speak_iter(self, chunks, settings: Settings, on_line: Callable | None = None): ...
    def warmup(self, settings: Settings) -> None: ...
    def stop(self) -> None: ...
    def close(self) -> None: ...

class WeatherPort(Protocol):
    def snapshot(self) -> dict: ...
    def reset(self, city: str) -> None: ...
    def accept_live(self, values: dict) -> None: ...

class TelemetryPort(Protocol):
    def sample(self) -> dict: ...

CloudFactory = Callable[[Settings], CloudGateway]
SettingsWriter = Callable[[Settings], None]

@dataclass(frozen=True)
class SessionServices:
    store: ConversationRepository
    audio: AudioPort
    cloud_factory: CloudFactory
    save_settings: SettingsWriter
    weather: WeatherPort
    telemetry: TelemetryPort
    wake_factory: Callable | None = None
